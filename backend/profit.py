"""Profit math — Python reference implementation.

The GitHub Pages site runs the JS port of this module (../profit.js); the two
must stay in sync. backend/scripts/parity_check.cjs verifies that over parity
fixtures generated by scripts/gen_fixtures.py. Keep both files in lockstep.
"""
import math

import config


def ge_tax(sell_price: int) -> int:
    """Grand Exchange tax on one item sold at sell_price.

    2% of the sale price, rounded down; items selling below 50 gp are
    effectively exempt (floor would be < 1 coin), capped at 5,000,000 gp per item.
    """
    if sell_price is None or sell_price < config.GE_TAX_EXEMPT_BELOW:
        return 0
    return min(math.floor(sell_price * config.GE_TAX_RATE), config.GE_TAX_CAP)


def _side(price_resolved, mode: str, kind: str):
    """price_resolved: store.resolve() output. Returns (value, stale, source, vol, vol_src)."""
    if kind == "buy":
        side = "high" if mode == "conservative" else "low"
        vol = "high_vol" if mode == "conservative" else "low_vol"
    else:
        side = "low" if mode == "conservative" else "high"
        vol = "low_vol" if mode == "conservative" else "high_vol"
    value, stale, source = price_resolved[side]
    v, vsrc = price_resolved[vol]
    return value, stale, source, v, vsrc


def evaluate_recipe(recipe: dict, item_map: dict, store, mode: str = "conservative",
                    craft_costs: dict | None = None,
                    all_costs: dict | None = None) -> dict | None:
    """Compute one recipe row. Returns None only if item metadata is missing.

    Missing GE prices are tolerated: unpriced sides become None and the row
    still renders (partial craft costs + per-cost incomplete flags; HA/LA
    payouts come from the item's static value, so they need no live prices).

    Three acquisition costs are priced per row:
    - cost_direct: buy every material at the GE, craft only the main product.
      Unavailable (None) when any material has no GE price — it cannot be bought.
    - cost: cheapest mix — per material the cheaper of buying it or crafting
      it (craft_costs: the recursive cheapest craft decomposition). Partial
      when a material is neither buyable nor craftable: priced parts only.
    - cost_all: buy only the root materials at the deepest recursion level and
      craft every intermediate (all_costs: recursive craft-everything cost;
      materials without one are bought). Partial like cost.

    recipe: {id, skill, level, members, product: {item_id, qty},
             materials: [{item_id, qty}], fee, note}
    item_map: {item_id: {name, members, buy_limit, value}}
    store: PriceStore-like (resolve(item_id) -> per-side tuples or None)
    """
    prod_info = item_map.get(recipe["product"]["item_id"])
    if prod_info is None:
        return None
    prod_res = store.resolve(recipe["product"]["item_id"])
    sell_price = sell_stale = sell_src = sell_vol = None
    prod_buy = prod_buy_stale = prod_buy_src = prod_buy_vol = None
    if prod_res is not None:
        sell_price, sell_stale, sell_src, sell_vol, _ = _side(prod_res, mode, "sell")
        prod_buy, prod_buy_stale, prod_buy_src, prod_buy_vol, _ = _side(prod_res, mode, "buy")

    materials = []
    fee = float(recipe.get("fee", 0))
    cost = fee        # mix: cheapest of buy vs craft per material
    cost_direct = fee    # direct: buy every material, craft only the main product
    cost_all = fee    # all: buy roots, craft every intermediate
    cost_known = direct_known = all_known = False
    cost_incomplete = direct_incomplete = all_incomplete = False
    min_mat_vol = None
    for m in recipe["materials"]:
        info = item_map.get(m["item_id"])
        if info is None:
            return None
        res = store.resolve(m["item_id"])
        buy_price = buy_stale = buy_src = buy_vol = None
        mat_sell = None
        if res is not None:
            buy_price, buy_stale, buy_src, buy_vol, _ = _side(res, mode, "buy")
            mat_sell, _, _, _, _ = _side(res, mode, "sell")
        craft_unit = round(craft_costs[m["item_id"]]) if craft_costs and m["item_id"] in craft_costs else None
        all_unit = round(all_costs[m["item_id"]]) if all_costs and m["item_id"] in all_costs else None
        # direct: the material is always bought at the GE price; a material
        # with no price cannot be bought, killing the whole option
        if buy_price is not None:
            cost_direct += buy_price * m["qty"]
            direct_known = True
        else:
            direct_incomplete = True
        # cheapest acquisition for this material: buy at GE price, or craft it if
        # that is cheaper; a material with neither leaves the cost incomplete
        if craft_unit is not None and (buy_price is None or craft_unit < buy_price):
            chosen = craft_unit
        elif buy_price is not None:
            chosen = buy_price
        else:
            chosen = None
            cost_incomplete = True
        if chosen is not None:
            cost += chosen * m["qty"]
            cost_known = True
        # craft-all: always craft craftable materials (even when buying is
        # cheaper — that is the scenario being priced); buy the rest
        if all_unit is not None:
            chosen_all = all_unit
        elif buy_price is not None:
            chosen_all = buy_price
        else:
            chosen_all = None
            all_incomplete = True
        if chosen_all is not None:
            cost_all += chosen_all * m["qty"]
            all_known = True
        materials.append({
            "id": m["item_id"],
            "name": info["name"],
            "image_url": info.get("image_url"),
            "qty": m["qty"],
            "price": buy_price,
            "stale": buy_stale,
            "source": buy_src,
            "vol": buy_vol,
            "sell": mat_sell,
            "sell_tax": ge_tax(mat_sell) if mat_sell is not None else 0,
            "craft": craft_unit,
        })
        if buy_vol is not None:
            # how many crafts per 5m does this material's buy-side volume support?
            supported = buy_vol / m["qty"] if m["qty"] > 0 else float('inf')
            min_mat_vol = supported if min_mat_vol is None else min(min_mat_vol, supported)

    if not cost_known:
        cost = None
    if not direct_known or direct_incomplete:
        cost_direct = None  # every material must be buyable for direct
    if not all_known:
        cost_all = None
    gross = sell_price * recipe["product"]["qty"] if sell_price is not None else None
    tax_total = ge_tax(sell_price) * recipe["product"]["qty"] if sell_price is not None else None
    net = None if (gross is None or cost is None) else gross - tax_total - cost
    net_pct = round(net / cost * 100, 1) if (net is not None and cost and cost > 0) else None

    # 4h buy-limit cap: limited by every material and the product itself
    max_crafts = None
    limited = False
    for m in recipe["materials"]:
        limit = item_map[m["item_id"]]["buy_limit"]
        if limit is None:
            limited = True
            continue
        c = limit // m["qty"]
        max_crafts = c if max_crafts is None else min(max_crafts, c)
    prod_limit = prod_info["buy_limit"]
    if prod_limit is None:
        limited = True
    else:
        c = prod_limit // recipe["product"]["qty"]
        max_crafts = c if max_crafts is None else min(max_crafts, c)
    if max_crafts is None:
        max_crafts = None  # no buy limits known at all
    net_4h = None if (limited or not max_crafts or net is None) else net * max_crafts

    volume = None
    if sell_vol is not None:
        volume = int(min(sell_vol, min_mat_vol)) if min_mat_vol is not None else int(sell_vol)

    tools_out = []
    for t in recipe.get("tools") or []:
        entry = {"id": t.get("item_id"), "name": t.get("name"), "image_url": None,
                 "buy": None, "buy_vol": 0, "sell": None, "tax": 0}
        if entry["id"] and entry["id"] in item_map:
            info = item_map[entry["id"]]
            entry["image_url"] = info.get("image_url")
            res = store.resolve(entry["id"])
            if res:
                entry["buy"] = res["high"][0]
                entry["buy_vol"] = res["high_vol"][0]
                entry["sell"] = res["low"][0]
                entry["tax"] = ge_tax(res["low"][0]) if res["low"][0] is not None else 0
        tools_out.append(entry)

    return {
        "recipe_id": recipe["id"],
        "skill": recipe["skill"],
        "level": recipe["level"],
        "extra_skills": recipe.get("extra_skills") or [],
        "xp": recipe.get("xp", 0),
        "members": recipe["members"],
        "product": {
            "id": prod_info["id"],
            "name": prod_info["name"],
            "image_url": prod_info.get("image_url"),
            "qty": recipe["product"]["qty"],
            "price": sell_price,
            "buy": prod_buy,
            "buy_vol": prod_buy_vol,
            "value": prod_info.get("value"),
            "stale": sell_stale,
            "source": sell_src,
            "vol": sell_vol,
        },
        "materials": materials,
        "fee": recipe.get("fee", 0),
        "cost_direct": round(cost_direct) if cost_direct is not None else None,
        "direct_incomplete": direct_incomplete,
        "cost": round(cost) if cost is not None else None,
        "cost_incomplete": cost_incomplete,
        "cost_all": round(cost_all) if cost_all is not None else None,
        "all_incomplete": all_incomplete,
        "gross": gross,
        "tax": tax_total,
        "net": round(net) if net is not None else None,
        "net_pct": net_pct,
        "volume": max(volume, 0) if volume is not None else None,
        "max_crafts_4h": max_crafts,
        "net_4h": round(net_4h) if net_4h is not None else None,
        "mode": mode,
        "note": recipe.get("note"),
        "tools": tools_out,
        "facilities": recipe.get("facilities") or [],
    }


def evaluate_all(recipes: list[dict], item_map: dict, store, mode: str = "conservative"):
    """Evaluate every recipe (the old /api/recipes route logic, minus filters).

    Craft costs are computed to a fixed point: repeated sweeps until no
    product's per-unit cost improves. craft_costs holds the cheapest mix
    (per material: buy or recursive craft), so a material's ⚒ price always
    equals the fully recursive cheapest craft decomposition shown in its own
    row (and expanded in the detail table) — e.g. Uncooked pizza inside Plain
    pizza prices cheese via milk, not at the cheese GE price. all_costs holds
    the craft-everything decomposition (roots bought, every intermediate
    crafted). Each sweep can only lower costs (materials gain cheaper
    options), so this converges; the sweep cap just bounds pathological
    recipe cycles. Keep in lockstep with ../profit.js (scripts/parity_check.cjs
    verifies over fixtures).

    Returns (rows, skipped_no_price).
    """
    material_ids = {m["item_id"] for r in recipes for m in r["materials"]}
    craft_costs: dict[int, float] = {}
    all_costs: dict[int, float] = {}
    max_sweeps = 10
    for _sweep in range(max_sweeps):
        changed = False
        for r in recipes:
            pid = r["product"]["item_id"]
            if pid not in material_ids:
                continue
            row = evaluate_recipe(r, item_map, store, mode=mode,
                                  craft_costs=craft_costs, all_costs=all_costs)
            if row is None or row["product"]["qty"] < 1:
                continue
            for key, costs in (("cost", craft_costs), ("cost_all", all_costs)):
                if row[key] is None:
                    continue
                per_unit = row[key] / row["product"]["qty"]
                if pid not in costs or per_unit < costs[pid]:
                    costs[pid] = per_unit
                    changed = True
        if not changed:
            break

    rows, skipped_no_price = [], 0
    for r in recipes:
        row = evaluate_recipe(r, item_map, store, mode=mode,
                              craft_costs=craft_costs, all_costs=all_costs)
        if row is None:
            skipped_no_price += 1
            continue
        rows.append(row)
    return rows, skipped_no_price
